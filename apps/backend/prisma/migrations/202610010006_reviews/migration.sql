BEGIN;

ALTER TABLE orders ADD COLUMN delivery_note TEXT NOT NULL DEFAULT '';
ALTER TABLE orders ADD CONSTRAINT ck_delivery_note_length
    CHECK (length(delivery_note) <= 500);

CREATE TABLE reviews (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL UNIQUE REFERENCES orders(id),
    rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment TEXT NOT NULL CHECK (length(btrim(comment)) BETWEEN 1 AND 2000),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE FUNCTION check_review_order() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE ordered_at TIMESTAMP; current_status TEXT;
BEGIN
    SELECT order_date, delivery_status INTO ordered_at, current_status
    FROM orders WHERE id = NEW.order_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Замовлення не знайдено' USING ERRCODE = '23503';
    END IF;
    IF current_status <> 'доставлено' THEN
        RAISE EXCEPTION 'Відгук дозволено лише після доставки'
            USING ERRCODE = '23514';
    END IF;
    IF NEW.created_at < ordered_at THEN
        RAISE EXCEPTION 'Дата відгуку передує замовленню'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER reviews_order_check BEFORE INSERT OR UPDATE ON reviews
FOR EACH ROW EXECUTE FUNCTION check_review_order();

